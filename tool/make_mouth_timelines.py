#!/usr/bin/env python3
"""Time the companion's mouth to each recorded line.

For every generated line in each language under
`with_me/assets/audio/voice/<language>/` (see make_voice_lines.py), this
measures how loud the voice is in each
1/30 s and picks a mouth for it: closed in the pauses, a small shape for
quiet sounds, a wider one for louder sounds, and the widest for the loudest.
Each new syllable moves to the next shape in its group, and every other
syllable after a pause starts on pressed lips, so the mouth keeps changing
the way speech does. It is not lip-sync, but it opens and closes with the
voice.

The result is written as Dart, `with_me/lib/WithMe/Speech/MouthTimelines.dart`:
one string per recording, one character per 1/30 s (see `MouthShape.code`).
Run it again whenever a recording changes. Needs ffmpeg on the PATH.

    python -m pip install numpy
    python tool/make_mouth_timelines.py
"""

from __future__ import annotations

import os
import subprocess

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
AUDIO_ROOT = os.path.join(HERE, '..', 'with_me', 'assets', 'audio')
# The folders of spoken lines: the check-in pages and the home greeting in
# each generated language.
FOLDERS = []
VOICE = os.path.join(AUDIO_ROOT, 'voice')
if os.path.isdir(VOICE):
    for language in sorted(os.listdir(VOICE)):
        for folder in ('checkin', 'home'):
            if os.path.isdir(os.path.join(VOICE, language, folder)):
                FOLDERS.append(f'voice/{language}/{folder}')
OUT = os.path.join(HERE, '..', 'with_me', 'lib', 'WithMe', 'Speech',
                   'MouthTimelines.dart')
FPS = 30
RATE = 16000

# One character per shape; MouthShape.code in RealMascot.dart matches.
CODE = {'closed': '.', 'mbp': 'm', 'mid': '1', 'wide': '2', 'ah': 'a',
        'ee': 'e', 'oh': 'o', 'oo': 'u', 'fv': 'f'}
GROUPS = {1: ['mid', 'fv', 'oo', 'ee'],
          2: ['wide', 'ee', 'oh', 'mid'],
          3: ['ah', 'wide', 'oh']}


def loudness(path: str) -> np.ndarray:
    raw = subprocess.run(
        ['ffmpeg', '-v', 'error', '-i', path, '-ac', '1', '-ar', str(RATE),
         '-f', 's16le', '-'], check=True, capture_output=True).stdout
    x = np.frombuffer(raw, np.int16).astype(float) / 32768
    step = RATE / FPS
    n = int(len(x) / step) + 1
    e = np.array([
        np.sqrt(np.mean(x[int(i * step):int((i + 1) * step)] ** 2))
        if int(i * step) < len(x) else 0.0 for i in range(n)])
    e = e / (e.max() or 1)
    return np.convolve(e, [0.25, 0.5, 0.25], 'same')


def level(v: float) -> int:
    return 0 if v < 0.05 else 1 if v < 0.2 else 2 if v < 0.45 else 3


def timeline(e: np.ndarray) -> str:
    out, syllable, current, hold, before = [], 0, 'closed', 0, 0
    for v in e:
        lv = level(v)
        if hold > 0 and lv != 0:
            hold -= 1
        elif lv == 0:
            current = 'closed'
        else:
            if before == 0 and syllable % 2 == 1:
                current = 'mbp'
            else:
                group = GROUPS[lv]
                current = group[syllable % len(group)]
            syllable += 1
            hold = 2
        out.append(CODE[current])
        before = lv
    return ''.join(out).rstrip('.') or '.'


def main() -> None:
    lines = []
    for folder in FOLDERS:
        audio = os.path.join(AUDIO_ROOT, folder)
        for name in sorted(os.listdir(audio)):
            if not name.endswith('.mp3'):
                continue
            t = timeline(loudness(os.path.join(audio, name)))
            lines.append(f"  'audio/{folder}/{name}':\n      '{t}',")
            print(f'{folder}/{name}: {len(t)} frames')
    with open(OUT, 'w') as f:
        f.write('''// Generated by tool/make_mouth_timelines.py from the recordings in
// assets/audio/voice/. Do not edit by hand: change a recording, then run
// the script again.

/// Frames per second of every timeline in [kMouthTimelines].
const int kMouthTimelineFps = 30;

/// The companion's mouth for each recorded line, by asset path: one
/// character per 1/30 s, as `MouthShape.code` reads them. After the last
/// character the mouth is closed.
const Map<String, String> kMouthTimelines = {
''' + '\n'.join(lines) + '\n};\n')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
